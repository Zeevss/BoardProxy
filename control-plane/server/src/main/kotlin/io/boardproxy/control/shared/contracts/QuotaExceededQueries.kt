 * конфигурации), а реализует телеметрия, и ни один из контекстов не должен
 * знать о другом. Прежде телеметрия вместо этого писала DISABLED прямо в
 * каталог — единственная связка, из-за которой превышение было необратимым.
 */
fun interface QuotaExceededQueries {
    fun exceededUsers(): Set<String>
}
